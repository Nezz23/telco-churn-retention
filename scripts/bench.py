"""Inference benchmark over real HTTP: throughput and p50/p95/p99 latency by batch size, concurrency and worker count.

Starts its own uvicorn server per worker count, so nothing else should be running. Writes reports/benchmark.json
(served by /ops) and docs/benchmarks.md. Usage: python scripts/bench.py [--seconds 8]
"""

import argparse
import asyncio
import json
import os
import platform
import subprocess
import sys
import time
from datetime import UTC, datetime
from pathlib import Path

import httpx
import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from churn import registry  # noqa: E402
from churn.data import load  # noqa: E402

PORT = 8799
SCENARIOS = [(1, 1), (1, 8), (1, 32), (10, 8), (100, 4), (1000, 2)]  # (customers per request, concurrent clients)


async def run(url, rows, batch, clients, seconds):
    latencies, stop = [], time.perf_counter() + seconds
    async with httpx.AsyncClient(timeout=60, limits=httpx.Limits(max_connections=clients)) as client:

        async def worker(k):
            i = k * 997
            while time.perf_counter() < stop:
                body = rows[(i * batch) % (len(rows) - batch) :][:batch]
                t = time.perf_counter()
                (await client.post(url, json=body)).raise_for_status()
                latencies.append((time.perf_counter() - t) * 1000)
                i += clients

        for _ in range(2):  # warm-up, discarded
            await client.post(url, json=rows[:batch])
        start = time.perf_counter()
        await asyncio.gather(*(worker(k) for k in range(clients)))
        elapsed = time.perf_counter() - start
    a = np.array(latencies)
    return {
        "batch": batch,
        "clients": clients,
        "requests": len(a),
        "seconds": round(elapsed, 2),
        "requests_per_s": round(len(a) / elapsed, 1),
        "predictions_per_s": round(len(a) * batch / elapsed, 0),
        **{f"p{q}_ms": round(float(np.percentile(a, q)), 1) for q in (50, 95, 99)},
    }


def serve(workers):
    proc = subprocess.Popen(
        [
            sys.executable,
            "-m",
            "uvicorn",
            "churn.api:app",
            "--port",
            str(PORT),
            "--workers",
            str(workers),
            "--log-level",
            "warning",
        ],
        stdout=subprocess.DEVNULL,
    )
    for _ in range(120):
        try:
            if httpx.get(f"http://127.0.0.1:{PORT}/health").status_code == 200:
                return proc
        except httpx.TransportError:
            time.sleep(0.25)
    proc.kill()
    raise RuntimeError("server did not start")


def in_process(rows):
    """Model-only cost (no HTTP, no JSON): scoring plus SHAP reasons for 1,000 customers."""
    model, _ = registry.load()
    X = pd.DataFrame(rows[:1000])
    times = []
    for _ in range(20):
        t = time.perf_counter()
        model.decide(X)
        model.contributions(X)
        times.append(time.perf_counter() - t)
    return {
        "customers": 1000,
        "median_ms": round(float(np.median(times)) * 1000, 1),
        "predictions_per_s": round(1000 / float(np.median(times)), 0),
    }


def markdown(r):
    env = r["environment"]
    lines = [
        "# Inference benchmarks",
        "",
        f"_Generated by `scripts/bench.py` on {r['created_at']}. Do not edit by hand._",
        "",
        f"**Machine:** {env['machine']}, {env['cpus']} logical CPUs, Python {env['python']}. Client and server share the "
        "machine, so the client's own CPU use is included. Every request returns calibrated scores, decisions and SHAP reasons. "
        f"Model {env['model_version']}. Each scenario runs for {env['seconds_per_scenario']} s after warm-up.",
        "",
        f"**Model only (no HTTP):** {r['in_process']['predictions_per_s']:,.0f} predictions/s "
        f"({r['in_process']['median_ms']} ms per 1,000 customers).",
        "",
    ]
    for w, rows in r["by_workers"].items():
        lines += [
            f"## {w} uvicorn worker{'s' if w != '1' else ''}",
            "",
            "| Customers / request | Concurrent clients | Requests/s | Predictions/s | p50 ms | p95 ms | p99 ms |",
            "|---|---|---|---|---|---|---|",
        ]
        lines += [
            f"| {s['batch']:,} | {s['clients']} | {s['requests_per_s']:,.0f} | {s['predictions_per_s']:,.0f} | "
            f"{s['p50_ms']} | {s['p95_ms']} | {s['p99_ms']} |"
            for s in rows
        ]
        lines.append("")
    lines += [
        "## Reading this",
        "",
        "- Single-customer requests are bound by per-request overhead (HTTP, validation, a pandas frame, SHAP); batching amortises it.",
        "- Deployment on a free-tier instance (a fraction of one CPU) will be several times slower than this laptop; "
        "re-run the script against the target host to size it.",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seconds", type=float, default=8)
    ap.add_argument("--workers", type=int, nargs="+", default=[1, 4])
    args = ap.parse_args()
    df = load()
    rows = json.loads(df.drop(columns=["Churn", "churned", "TotalCharges"]).to_json(orient="records"))
    result = {
        "created_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "environment": {
            "machine": platform.processor() or platform.machine(),
            "platform": platform.platform(),
            "cpus": os.cpu_count(),
            "python": platform.python_version(),
            "model_version": registry.index()["champion"],
            "seconds_per_scenario": args.seconds,
        },
        "in_process": in_process(rows),
        "by_workers": {},
    }
    for w in args.workers:
        proc = serve(w)
        try:
            result["by_workers"][str(w)] = [
                asyncio.run(run(f"http://127.0.0.1:{PORT}/predict", rows, b, c, args.seconds)) for b, c in SCENARIOS
            ]
        finally:
            proc.terminate()
            proc.wait()
        for s in result["by_workers"][str(w)]:
            print(w, s)
    mac = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True, text=True).stdout.strip()
    if mac:
        result["environment"]["machine"] = mac
    Path("reports/benchmark.json").write_text(json.dumps(result, indent=2) + "\n")
    Path("docs").mkdir(exist_ok=True)
    Path("docs/benchmarks.md").write_text(markdown(result))


if __name__ == "__main__":
    main()
